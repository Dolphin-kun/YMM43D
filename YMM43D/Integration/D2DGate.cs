namespace YMM43D.Integration
{
    /// <summary>
    /// Direct2D の操作を、このプラグイン全体で1本に直列化するための鍵。
    /// </summary>
    /// <remarks>
    /// <para>
    /// <c>ID2D1DeviceContext</c> はスレッド安全ではありません。描画先・変換・描画中状態を
    /// 内部に持つため、2つのスレッドから同時に呼ぶと状態が壊れます。壊れ方は運任せで、
    /// 良くて <c>D2DERR_WRONG_STATE</c>、悪ければ vtable 経由の呼び出しがアクセス違反を
    /// 起こし、<c>ExecutionEngineException</c> としてプロセスごと落ちます。
    /// </para>
    /// <para>
    /// このプラグインは 3Dプレビューを本体とは別のスレッドで回すため、同じコンテキストを
    /// 2方向から使う場面が生まれます。たとえば映像エフェクトのプロセッサは、本体の
    /// 描画スレッドから <c>Update</c> を、プレビューのスレッドから <c>GetTexture</c> を
    /// 呼ばれ、どちらも入力画像の範囲を調べます。
    /// </para>
    /// <para>
    /// 資源はコンテキストではなくデバイスに属するので、鍵はデバイスごとではなく
    /// 全体で1つにしています。細かく分けても、同じデバイス上の資源を触る以上は
    /// 結局まとめて守る必要があります。
    /// </para>
    /// <para>
    /// <b>守る範囲</b>：このプラグインが直接呼ぶ Direct2D だけでなく、3Dプレビューが
    /// アイテムの絵を得るために回す YMM4 本体の描画（<c>ISource.Update</c> や
    /// エフェクト連鎖）も含めます。あれも同じデバイスを使うため、外に置くと
    /// 本体の描画スレッドと並走してしまいます。
    /// </para>
    /// <para>
    /// <b>入れ子の順序</b>：必ず「この鍵 → 3D描画用デバイス」の順で取ってください。
    /// 逆順に取る箇所を1つでも作ると詰まります。
    /// </para>
    /// </remarks>
    public static class D2DGate
    {
        /// <summary>Direct2D の操作を囲む鍵。</summary>
        public static readonly Lock Sync = new();
    }
}
